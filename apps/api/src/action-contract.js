function freezeAction(action) {
  return Object.freeze({
    ...action,
    entryPoints: Object.freeze([...action.entryPoints]),
    failureOutcome: Object.freeze([...action.failureOutcome]),
  });
}

const ACTION_CATALOG = Object.freeze(ACTIONS.map(freezeAction));
const ACTION_BY_ID = new Map(ACTION_CATALOG.map((action) => [action.actionId, action]));

export function listActionContracts(options = {}) {
  const includePlanned = options.includePlanned !== false;
  return ACTION_CATALOG.filter((action) => includePlanned || action.status === ACTION_STATUS.IMPLEMENTED);
}

export function getActionContract(actionId) {
  return ACTION_BY_ID.get(String(actionId || "").trim()) || null;
}

export function describeActionContract(actionId) {
  const action = getActionContract(actionId);
  if (!action) return null;
  return {
    contractVersion: ACTION_CONTRACT_VERSION,
    ...action,
    sideEffectClass: action.status === ACTION_STATUS.PLANNED ? "planned" : action.sideEffectClass,
    diagnostics: {
      semanticDestination: true,
      uiRoute: false,
      automaticHandoff: action.handoffPolicy !== HANDOFF_POLICIES.NONE,
      businessScopeRequired: action.businessScopeRequirement === "required",
    },
  };
}
